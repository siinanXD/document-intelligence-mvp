"""Small first-slice classification fixture chosen from the SIN-88/SIN-99 set.

The members are generated by the same conveyor-line oracle. This module does
not invent a second package; it names the schematic / manual / BOM / PLC
subset SIN-90 must classify.
"""

from __future__ import annotations

from app.engineering_models import EngineeringDocumentClass
from app.evaluation.machine_intelligence.artifacts import binary_files
from app.evaluation.machine_intelligence.line import MACHINE_CODE, MACHINE_NAME

CLASSIFICATION_FIXTURE_MEMBERS: tuple[str, ...] = (
    "overview.md",
    "schematic.pdf",
    "bom.xlsx",
    "plc/OB1.xml",
    "unrelated_hvac.md",
)

EXPECTED_CLASSES: dict[str, EngineeringDocumentClass] = {
    "": EngineeringDocumentClass.package_container,
    "overview.md": EngineeringDocumentClass.manual,
    "schematic.pdf": EngineeringDocumentClass.schematic,
    "bom.xlsx": EngineeringDocumentClass.bom,
    "plc/OB1.xml": EngineeringDocumentClass.plc_xml,
    "unrelated_hvac.md": EngineeringDocumentClass.unrelated,
}

EXPECTED_MACHINE: dict[str, str | None] = {
    "": MACHINE_CODE,
    "overview.md": MACHINE_CODE,
    "schematic.pdf": MACHINE_CODE,
    "bom.xlsx": MACHINE_CODE,
    "plc/OB1.xml": MACHINE_CODE,
    "unrelated_hvac.md": None,
}


def classification_fixture_files() -> dict[str, bytes]:
    """Schematic, manual, BOM and PLC bytes from the SIN-99 generator."""
    files = binary_files()
    return {name: files[name] for name in CLASSIFICATION_FIXTURE_MEMBERS}


def expected_machine_name() -> str:
    return MACHINE_NAME
